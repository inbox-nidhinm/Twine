#!/usr/bin/env python3
"""Turn a directory of SVG icons into a Swift `Icon` enum of path data.

Pairs with assets/IconShape.swift, which parses the emitted strings once and
strokes them at any size: so the icons scale and tint like SF Symbols without
an asset catalogue or any image resources.

Usage
-----
    python3 svg_to_swift.py --icons Icons --out Sources/App/UI/Icons.swift

By default every .svg under --icons becomes a case, named by camel-casing the
filename and prefixing the folder when --prefix-folders is given. To control the
names (recommended: filenames from an icon library rarely match your domain),
write a map and pass --map:

    {
      "Tools/cursor-02.svg":     "cursor",
      "Tools/pen-tool-03.svg":   "pen",
      "Bottom Bar/copy-01.svg":  "thisFrame"
    }

Files present but absent from the map are skipped, and names in the map with no
file are an error: so the map doubles as a checklist while artwork arrives in
batches.

Validation
----------
Fails loudly rather than emitting art that will draw wrong:
  * viewBox must be the expected square grid (default 0 0 24 24)
  * at least one path
  * only path commands the Swift parser implements (M L H V C Z)

If an icon uses arcs (A) or quadratics (Q), either ask for it re-exported with
cubic curves, or implement the command in BOTH this file's ALLOWED set and
IconShape.swift's parser.
"""

import argparse
import json
import pathlib
import re
import sys

VIEWBOX = re.compile(r'viewBox="([^"]*)"')
D = re.compile(r'\sd="([^"]*)"')
ALLOWED = set("MLHVCZmlhvcz")


def camel(stem: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", stem)
    parts = [p for p in parts if p]
    if not parts:
        raise SystemExit(f"cannot make a name from {stem!r}")
    head, *rest = parts
    return head[0].lower() + head[1:] + "".join(p[:1].upper() + p[1:] for p in rest)


def read_paths(path: pathlib.Path, grid: int):
    text = path.read_text()

    box = VIEWBOX.search(text)
    want = ["0", "0", str(grid), str(grid)]
    if not box or box.group(1).split() != want:
        raise SystemExit(
            f"{path}: expected viewBox '0 0 {grid} {grid}', got {box and box.group(1)!r}"
        )

    ds = D.findall(text)
    if not ds:
        raise SystemExit(f"{path}: no <path d=...> found")

    for d in ds:
        for ch in d:
            if ch.isalpha() and ch not in ALLOWED:
                raise SystemExit(
                    f"{path}: path command {ch!r} is not supported.\n"
                    "  The Swift parser implements M L H V C Z. Re-export this icon "
                    "with cubic curves, or extend both this script and IconShape.swift."
                )
    return ds


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--icons", required=True, help="directory of .svg files")
    ap.add_argument("--out", required=True, help="Swift file to write")
    ap.add_argument("--map", help="JSON of {relative path: swift case name}")
    ap.add_argument("--grid", type=int, default=24, help="viewBox edge (default 24)")
    ap.add_argument("--prefix-folders", action="store_true",
                    help="prefix generated names with their folder")
    args = ap.parse_args()

    root = pathlib.Path(args.icons)
    if not root.is_dir():
        raise SystemExit(f"{root}: not a directory")

    if args.map:
        mapping = json.loads(pathlib.Path(args.map).read_text())
        missing = [rel for rel in mapping if not (root / rel).exists()]
        if missing:
            raise SystemExit("mapped but not found:\n  " + "\n  ".join(sorted(missing)))
        pairs = [(name, root / rel, rel) for rel, name in mapping.items()]
    else:
        pairs = []
        for f in sorted(root.rglob("*.svg")):
            rel = f.relative_to(root)
            stem = f"{rel.parent.name}-{f.stem}" if args.prefix_folders and rel.parent.name != "." else f.stem
            pairs.append((camel(stem), f, str(rel)))

    if not pairs:
        raise SystemExit(f"no SVGs found under {root}")

    seen = {}
    for name, _, rel in pairs:
        if name in seen:
            raise SystemExit(f"duplicate case name {name!r}: {seen[name]} and {rel}")
        seen[name] = rel

    grid = args.grid
    out = [
        "// Generated by svg_to_swift.py. Do not edit by hand.",
        f"// Source artwork lives in {args.icons}/. Re-run the script after changing it.",
        "",
        "import SwiftUI",
        "",
        f"/// The app's icon set, as SVG path data on a {grid}×{grid} grid.",
        "///",
        "/// Parsed once on first use and cached. See `IconShape` for the drawing.",
        "public enum Icon: String, CaseIterable, Sendable {",
    ]
    out += [f"    case {name}" for name, _, _ in pairs]
    out += ["", "    /// The subpaths, in the order they are drawn.",
            "    public var data: [String] {", "        switch self {"]

    for name, path, rel in pairs:
        ds = read_paths(path, grid)
        out.append(f"        case .{name}: return [   // {rel}")
        out.append(",\n".join(f'            "{d}"' for d in ds))
        out.append("        ]")

    out += ["        }", "    }", "}", ""]

    dest = pathlib.Path(args.out)
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(out))
    print(f"wrote {dest}: {len(pairs)} icons")


if __name__ == "__main__":
    main()
